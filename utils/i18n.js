const getLang = () => localStorage.getItem('app_lang') || 'ro';

export function t(key) {
    const lang = getLang();
    return DICT[lang]?.[key] || DICT.ro?.[key] || key;
}

export function applyLang(lang) {
    if (!DICT[lang]) lang = 'ro';
    localStorage.setItem('app_lang', lang);
    document.documentElement.lang = lang;

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.dataset.i18n;
        // ✅ Eliminăm check-ul care bloca actualizarea după prima randare MathJax
        if (DICT[lang][key] !== undefined && !el.querySelector('script')) {
            // Curățăm containerele MathJax vechi
            el.querySelectorAll('mjx-container').forEach(m => m.remove());
            // ✅ innerHTML permite <br> și formule să funcționeze la fiecare switch
            el.innerHTML = DICT[lang][key];
        }
    });

    document.querySelectorAll('.lang-link').forEach(btn => {
        btn.classList.toggle('active', btn.dataset.lang === lang);
    });

    if (window.MathJax?.typesetPromise) {
        requestAnimationFrame(() => MathJax.typesetPromise().catch(() => {}));
    }
}

export function initLangSwitcher() {
    const saved = localStorage.getItem('app_lang') || 'ro';
    applyLang(saved);
    document.querySelectorAll('.lang-link').forEach(btn => {
        btn.addEventListener('click', (e) => {
            e.preventDefault();
            applyLang(btn.dataset.lang);
        });
    });
}
